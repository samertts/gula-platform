#!/usr/bin/env bash
set -euo pipefail

# ──────────────────────────────────────────────────────────────────────────────
# GULA Platform — Contract Generation Script
#
# Usage:  ./scripts/generate-contracts.sh
#
# Generates all platform contracts (OpenAPI, AsyncAPI, JSON Schema, FHIR R4,
# GraphQL) and saves them to the contracts/ directory.
# ──────────────────────────────────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
CONTRACTS_DIR="${REPO_ROOT}/contracts"
BACKEND_DIR="${REPO_ROOT}/backend"
VENV_DIR="${BACKEND_DIR}/venv"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

info()  { echo -e "${GREEN}[INFO]${NC} $*"; }
warn()  { echo -e "${YELLOW}[WARN]${NC} $*"; }
error() { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }

# ── 1. Locate Python venv ────────────────────────────────────────────────────
activate_venv() {
    if [ -d "${VENV_DIR}" ] && [ -f "${VENV_DIR}/bin/activate" ]; then
        info "Activating venv at ${VENV_DIR}"
        # shellcheck disable=SC1091
        source "${VENV_DIR}/bin/activate"
    elif [ -d "${BACKEND_DIR}/.venv" ] && [ -f "${BACKEND_DIR}/.venv/bin/activate" ]; then
        info "Activating venv at ${BACKEND_DIR}/.venv"
        # shellcheck disable=SC1091
        source "${BACKEND_DIR}/.venv/bin/activate"
    else
        # Try to find any Python with required modules
        if python3 -c "import fastapi, pydantic" 2>/dev/null; then
            info "Using system Python 3 (fastapi+pydantic available)"
            PYTHON_CMD="python3"
            return
        fi
        error "No Python venv found at ${VENV_DIR} or ${BACKEND_DIR}/.venv. Run setup-venv.sh first."
    fi

    PYTHON_CMD="python"
}

# ── 2. Generate contracts ─────────────────────────────────────────────────────
generate_contracts() {
    info "Generating platform contracts..."
    mkdir -p "${CONTRACTS_DIR}"

    # Use Python to generate and export all contracts via the API
    "${PYTHON_CMD}" -c "
import sys
import os
sys.path.insert(0, '${BACKEND_DIR}')
os.environ.setdefault('ENV', 'development')
os.environ.setdefault('RUNTIME_MODE', 'cli')

from app.contracts.generator import ContractGenerator

gen = ContractGenerator()
exported = gen.export_all('${CONTRACTS_DIR}')
for path in exported:
    size = os.path.getsize(path)
    print(f'  {path} ({size:,} bytes)')
print(f'Total: {len(exported)} files')
"
}

# ── 3. Generate via API (alternative: curl to running server) ─────────────────
generate_via_api() {
    local base_url="${1:-http://localhost:8000}"
    info "Attempting contract export via API at ${base_url}..."

    if curl -sf "${base_url}/health" > /dev/null 2>&1; then
        mkdir -p "${CONTRACTS_DIR}"

        # Export via POST /contracts/export
        curl -sf -X POST "${base_url}/contracts/export" \
            -H "Content-Type: application/json" \
            -d "{\"output_dir\": \"${CONTRACTS_DIR}\", \"pretty\": true}" \
            > "${CONTRACTS_DIR}/export-response.json" 2>/dev/null && {
            info "API export succeeded"
            return 0
        }

        # Fallback: fetch each contract individually
        info "Fetching contracts individually..."
        for endpoint in openapi.json asyncapi.json; do
            curl -sf "${base_url}/contracts/${endpoint}" \
                -o "${CONTRACTS_DIR}/${endpoint}" && \
                info "  Downloaded ${endpoint}"
        done
        curl -sf "${base_url}/contracts/graphql/schema" \
            -o "${CONTRACTS_DIR}/graphql-schema.graphql" && \
            info "  Downloaded graphql-schema.graphql"
    else
        warn "API not running at ${base_url}. Use 'make up' first or run Python directly."
        return 1
    fi
}

# ── 4. Commit generated contracts (optional) ──────────────────────────────────
commit_contracts() {
    if ! git rev-parse --is-inside-work-tree > /dev/null 2>&1; then
        info "Not a git repository — skipping commit"
        return
    fi

    cd "${REPO_ROOT}"

    if git status --porcelain "${CONTRACTS_DIR}" | grep -q .; then
        info "Committing generated contracts..."
        git add "${CONTRACTS_DIR}"
        git commit -m "chore: regenerate platform contracts [CI skip]

Auto-generated by scripts/generate-contracts.sh
- $(git diff --cached --name-only -- "${CONTRACTS_DIR}" | wc -l) files updated"
        info "Committed contract updates"
    else
        info "No contract changes to commit"
    fi
}

# ── 5. Main ───────────────────────────────────────────────────────────────────
main() {
    echo ""
    info "GULA Platform — Contract Generator"
    info "=================================="
    echo ""

    activate_venv

    # Try API first (faster), fall back to direct generation
    if ! generate_via_api "${API_URL:-http://localhost:8000}"; then
        generate_contracts
    fi

    echo ""
    info "Contracts directory: ${CONTRACTS_DIR}"
    if [ -d "${CONTRACTS_DIR}" ]; then
        ls -lh "${CONTRACTS_DIR}"/*.json "${CONTRACTS_DIR}"/*.graphql 2>/dev/null || \
            ls -lh "${CONTRACTS_DIR}"
    fi
    echo ""

    if [ "${COMMIT:-false}" = "true" ]; then
        commit_contracts
    fi

    info "Done — ${#} contracts generated"
}

main "$@"
