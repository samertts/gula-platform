"""Phase 16 — Engine Registry.

Maintain the capabilities, compatibility, version, health, ownership,
communication, and dependency matrices for every governed engine. All
matrices derive from the single ENGINE_REGISTRY source of truth, so drift is
impossible by construction.
"""

from __future__ import annotations

from typing import Any

from .core import ENGINE_REGISTRY


def _matrix(registry: dict, field_name: str) -> dict[str, list[str]]:
    return {
        engine: list(meta.get(field_name, []))
        for engine, meta in registry.items()
    }


def capabilities(registry: dict | None = None) -> dict[str, list[str]]:
    registry = registry or ENGINE_REGISTRY
    return _matrix(registry, "capabilities")


def compatibility_matrix(registry: dict | None = None) -> dict[str, list[str]]:
    registry = registry or ENGINE_REGISTRY
    return _matrix(registry, "compatibility")


def version_matrix(registry: dict | None = None) -> dict[str, str]:
    registry = registry or ENGINE_REGISTRY
    return {engine: meta.get("version", "0.0.0") for engine, meta in registry.items()}


def health_matrix(registry: dict | None = None) -> dict[str, str]:
    registry = registry or ENGINE_REGISTRY
    return {engine: meta.get("health", "unknown") for engine, meta in registry.items()}


def ownership_matrix(registry: dict | None = None) -> dict[str, list[str]]:
    registry = registry or ENGINE_REGISTRY
    return _matrix(registry, "ownership")


def communication_matrix(registry: dict | None = None) -> dict[str, list[str]]:
    registry = registry or ENGINE_REGISTRY
    return _matrix(registry, "communication")


def dependency_matrix(registry: dict | None = None) -> dict[str, list[str]]:
    registry = registry or ENGINE_REGISTRY
    return _matrix(registry, "dependencies")


def all_matrices(registry: dict | None = None) -> dict[str, Any]:
    return {
        "capabilities": capabilities(registry),
        "compatibility": compatibility_matrix(registry),
        "versions": version_matrix(registry),
        "health": health_matrix(registry),
        "ownership": ownership_matrix(registry),
        "communication": communication_matrix(registry),
        "dependencies": dependency_matrix(registry),
    }


def render_matrices(registry: dict | None = None) -> str:
    """Render all matrices as a markdown report."""
    matrices = all_matrices(registry)
    lines = [
        "# ENGINE REGISTRY",
        "",
        "> Mission: GULA-KERNEL-001 — Phase 16: Engine Registry",
        "> Generated by: `scripts/kernel`",
        "",
    ]
    for matrix_name in ("capabilities", "ownership", "communication", "dependencies", "compatibility"):
        lines.append(f"## {matrix_name.title()} Matrix")
        lines.append("")
        lines.append("| Engine | Entries |")
        lines.append("|---|---|")
        for engine, entries in matrices[matrix_name].items():
            lines.append(f"| {engine} | {', '.join(entries) or '—'} |")
        lines.append("")
    lines.append("## Version Matrix")
    lines.append("")
    lines.append("| Engine | Version |")
    lines.append("|---|---|")
    for engine, version in matrices["versions"].items():
        lines.append(f"| {engine} | {version} |")
    lines.append("")
    lines.append("## Health Matrix")
    lines.append("")
    lines.append("| Engine | Health |")
    lines.append("|---|---|")
    for engine, health in matrices["health"].items():
        lines.append(f"| {engine} | {health} |")
    lines.append("")
    return "\n".join(lines) + "\n"
