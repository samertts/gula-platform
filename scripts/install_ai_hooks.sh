#!/bin/bash
# PROGRAM-AUTOMATION-001: Install AI Git Hooks
# Installs pre-commit and pre-push hooks for AI governance

set -e

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOKS_DIR="$REPO_ROOT/.git/hooks"
SCRIPTS_DIR="$REPO_ROOT/scripts"

echo "Installing GULA AI Git Hooks..."
echo "================================"

# Install pre-commit hook
PRE_COMMIT="$HOOKS_DIR/pre-commit"
if [ -f "$PRE_COMMIT" ]; then
    echo "Backing up existing pre-commit hook..."
    cp "$PRE_COMMIT" "$PRE_COMMIT.bak.$(date +%s)"
fi

cat > "$PRE_COMMIT" << 'HOOKEOF'
#!/bin/bash
# GULA AI Pre-commit Hook
# Generated by scripts/install_ai_hooks.sh

REPO_ROOT="$(git rev-parse --show-toplevel)"
SCRIPTS_DIR="$REPO_ROOT/scripts"

echo "[GULA-AI] Running pre-commit validation..."

# Run constitution validator (blocking)
if ! python3 "$SCRIPTS_DIR/validate_constitution.py" > /dev/null 2>&1; then
    echo "[GULA-AI] FAIL: Constitution validation failed"
    python3 "$SCRIPTS_DIR/validate_constitution.py" 2>&1 | grep -E "\[(FAIL|WARN)\]" | head -5
    echo "[GULA-AI] Commit blocked. Fix issues or use --no-verify to bypass."
    exit 1
fi

# Run knowledge validator (non-blocking, warn only)
if ! python3 "$SCRIPTS_DIR/validate_knowledge.py" > /dev/null 2>&1; then
    echo "[GULA-AI] WARN: Knowledge validation has warnings"
fi

echo "[GULA-AI] Pre-commit passed."
exit 0
HOOKEOF

chmod +x "$PRE_COMMIT"
echo "[OK] pre-commit hook installed"

# Install pre-push hook
PRE_PUSH="$HOOKS_DIR/pre-push"
if [ -f "$PRE_PUSH" ]; then
    echo "Backing up existing pre-push hook..."
    cp "$PRE_PUSH" "$PRE_PUSH.bak.$(date +%s)"
fi

cat > "$PRE_PUSH" << 'HOOKEOF'
#!/bin/bash
# GULA AI Pre-push Hook
# Generated by scripts/install_ai_hooks.sh

REPO_ROOT="$(git rev-parse --show-toplevel)"
SCRIPTS_DIR="$REPO_ROOT/scripts"

echo "[GULA-AI] Running pre-push validation..."

# Full AI system validation before push
if ! python3 "$SCRIPTS_DIR/validate_ai_system.py" --fast > /dev/null 2>&1; then
    echo "[GULA-AI] WARN: AI system validation has warnings (non-blocking for push)"
fi

echo "[GULA-AI] Pre-push passed."
exit 0
HOOKEOF

chmod +x "$PRE_PUSH"
echo "[OK] pre-push hook installed"

echo ""
echo "================================"
echo "GULA AI Git Hooks installed successfully!"
echo ""
echo "Hooks installed:"
echo "  - pre-commit: Constitution + Knowledge validation"
echo "  - pre-push: AI system validation"
echo ""
echo "To uninstall: rm .git/hooks/pre-commit .git/hooks/pre-push"
echo "To bypass: git commit --no-verify"
