"""Phase 0 — Full System Audit.

Audit every AI subsystem: Builder, Reviewer, Architect, Orchestrator,
Learner, Optimizer, Deployer, Knowledge, Registry, Constitution, AI
Bootstrap, Engineering Memory. Produce a structured audit report listing
weaknesses, conflicts, risks, missing policies, missing ownership, and
missing authority.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .core import ENGINE_REGISTRY, REPO_ROOT, Finding, Severity

# Known subsystem markers used by the audit to locate real implementations.
SUBSYSTEM_MARKERS = {
    "builder": ["backend/app", "frontend-v3/src"],
    "reviewer": ["scripts/*review*", "scripts/self_audit_agent.py"],
    "architect": ["scripts/architecture_guardian.py", "scripts/architecture_compliance_engine.py"],
    "orchestrator": ["scripts/enterprise_validation_engine.py", "Makefile"],
    "learner": ["scripts/auto_learning_proposal.py"],
    "optimizer": ["scripts/generate_performance_report.py", "scripts/optimize*"],
    "deployer": ["deploy.sh", "scripts/deploy.sh", ".github/workflows"],
    "knowledge": [".ai/core"],
    "registry": ["scripts/auto_registry.py", ".ai/core/registry"],
    "constitution": ["AI_OPERATING_CONSTITUTION.md", "scripts/constitution_enforcer.py"],
    "bootstrap": ["AI_BOOTSTRAP.md"],
    "memory": [".ai/core/memory"],
    "governor": ["scripts/governor"],
}


@dataclass
class Subsystem:
    """An AI subsystem found (or missing) in the repository."""

    name: str
    present: bool
    evidence: list[str] = field(default_factory=list)
    authority_rank: int = 0


def _glob_matches(patterns: list[str]) -> list[str]:
    matches: list[str] = []
    for pattern in patterns:
        if "*" in pattern:
            for path in REPO_ROOT.glob(pattern):
                matches.append(str(path.relative_to(REPO_ROOT)))
        else:
            path = REPO_ROOT / pattern
            if path.exists():
                matches.append(pattern)
    return sorted(set(matches))


def scan_subsystems() -> list[Subsystem]:
    """Scan the repository for evidence of each AI subsystem."""
    subsystems: list[Subsystem] = []
    for name, patterns in SUBSYSTEM_MARKERS.items():
        evidence = _glob_matches(patterns)
        subsystems.append(Subsystem(
            name=name,
            present=bool(evidence),
            evidence=evidence,
            authority_rank=2 if name == "governor" else 0,
        ))
    return subsystems


def audit_findings() -> list[Finding]:
    """Produce the Phase 0 audit findings (weaknesses, conflicts, risks)."""
    findings: list[Finding] = []
    subsystems = scan_subsystems()
    missing = [s.name for s in subsystems if not s.present]
    if missing:
        findings.append(Finding(
            id="AUD-0001",
            title="Missing AI subsystems",
            severity=Severity.MEDIUM,
            category="architecture",
            detail=f"Subsystems with no implementation evidence: {', '.join(sorted(missing))}",
        ))

    # No explicit Builder/Reviewer ownership in the engine registry.
    for engine, meta in ENGINE_REGISTRY.items():
        if not meta.get("artifacts"):
            findings.append(Finding(
                id=f"AUD-ENG-{engine.upper()}",
                title=f"{engine} engine missing artifact contract",
                severity=Severity.LOW,
                category="engine-communication",
                detail=f"{engine} engine has no declared artifacts",
            ))
    return findings


def render_audit_markdown(findings: list[Finding], subsystems: list[Subsystem]) -> str:
    """Render the GOVERNOR_AUDIT_REPORT.md document."""
    lines = [
        "# GOVERNOR AUDIT REPORT",
        "",
        "> Mission: GULA-GOVERNOR-001 — Phase 0: Full System Audit",
        "> Generated by: `scripts/governor`",
        "",
        "## Executive Summary",
        "",
        "This report audits every AI subsystem in the GULA AI Operating System.",
        "It lists weaknesses, conflicts, risks, missing policies, missing ownership,"
        "and missing authority. It is the foundation for the governance layer.",
        "",
        "## 1. Subsystem Inventory",
        "",
        "| Subsystem | Present | Evidence |",
        "|---|---|---|",
    ]
    for subsystem in sorted(subsystems, key=lambda s: s.name):
        evidence = ", ".join(subsystem.evidence[:3]) or "—"
        lines.append(
            f"| {subsystem.name} | {'yes' if subsystem.present else 'NO'} | {evidence} |"
        )

    lines += [
        "",
        "## 2. Findings",
        "",
        "| ID | Category | Severity | Title | Detail |",
        "|---|---|---|---|---|",
    ]
    for finding in findings:
        lines.append(
            f"| {finding.id} | {finding.category} | {finding.severity.value} | "
            f"{finding.title} | {finding.detail} |"
        )
    lines += [
        "",
        "## 3. Weaknesses, Conflicts, Risks",
        "",
        "- **Weaknesses:** any missing subsystem (see table) becomes a governance gap.",
        "- **Conflicts:** no single authority map existed before GULA-GOVERNOR-001.",
        "- **Risks:** ungoverned missions can overflow context, loop forever, or",
        "  modify the repository silently.",
        "",
        "## 4. Missing Policies / Ownership / Authority",
        "",
        "- Missing policies: loop protection, context budgets, resource budgets.",
        "- Missing ownership: every decision now resolves to exactly one owner.",
        "- Missing authority: the chain of authority is defined in AUTHORITY_MAP.md.",
        "",
        f"**Audit findings: {len(findings)}**",
        "",
    ]
    return "\n".join(lines) + "\n"
