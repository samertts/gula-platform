"""GULA Governor CLI — single entry point for all 14 phases.

Usage:
    python scripts/governor.py audit                  Phase 0 — write GOVERNOR_AUDIT_REPORT.md
    python scripts/governor.py authority              Phase 1 — write AUTHORITY_MAP.md
    python scripts/governor.py health                 Phase 12 — write AI_HEALTH_DASHBOARD.md
    python scripts/governor.py report                 Phase 13 — write GOVERNOR_IMPLEMENTATION_REPORT.md
    python scripts/governor.py check                  Run all Governor self-checks (exit 1 on failure)
"""

from __future__ import annotations

import sys

from . import audit, authority, health_dashboard, report
from .core import ENGINE_REGISTRY, REPO_ROOT


def run_audit() -> int:
    """Phase 0: produce GOVERNOR_AUDIT_REPORT.md at the repository root."""
    findings = audit.audit_findings()
    subsystems = audit.scan_subsystems()
    markdown = audit.render_audit_markdown(findings, subsystems)
    path = REPO_ROOT / "docs/reports/GOVERNOR_AUDIT_REPORT.md"
    path.write_text(markdown, encoding="utf-8")
    print(f"[OK] GOVERNOR_AUDIT_REPORT.md written ({len(findings)} findings)")
    return 0


def run_authority() -> int:
    """Phase 1: produce AUTHORITY_MAP.md under docs/architecture/."""
    markdown = authority_map_markdown()
    path = REPO_ROOT / "docs" / "architecture" / "AUTHORITY_MAP.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown, encoding="utf-8")
    print("[OK] AUTHORITY_MAP.md written")
    return 0


def authority_map_markdown() -> str:
    """Render the AUTHORITY_MAP.md document from the authority chain."""
    chain = authority.chain_summary()
    lines = [
        "# AUTHORITY MAP",
        "",
        "> Mission: GULA-GOVERNOR-001 — Phase 1: Chain of Authority",
        "> Generated by: `scripts/governor`",
        "",
        "## Immutable Chain of Authority",
        "",
        "Every decision has exactly one owner. No engine may override a higher",
        "authority. The Constitution is the supreme authority.",
        "",
        "```",
    ]
    for i, entry in enumerate(chain):
        engine = entry["engine"].capitalize()
        lines.append(f"{i}. {engine}")
        if i < len(chain) - 1:
            lines.append("   ↓")
    lines += [
        "```",
        "",
        "## Ownership Rules",
        "",
        "| Category | Owner | Rule |",
        "|---|---|---|",
        "| Architecture / ADR / API contract | Architect | Only the Architect may approve architectural decisions |",
        "| Deployment / Release | Reviewer | Only the Reviewer may approve deployments |",
        "| Everything else | Governor | The Governor owns unassigned decisions |",
        "",
        "## Override Rules",
        "",
        "- A higher-authority engine may override a lower one.",
        "- A lower-authority engine MUST NOT override a higher one.",
        "- Escalation always moves UP the chain.",
        "",
    ]
    return "\n".join(lines) + "\n"


def run_health() -> int:
    """Phase 12: produce AI_HEALTH_DASHBOARD.md at the repository root."""
    path = health_dashboard.write_dashboard()
    print(f"[OK] {path} written")
    return 0


def run_report() -> int:
    """Phase 13: produce GOVERNOR_IMPLEMENTATION_REPORT.md at the repository root."""
    path = report.write_report()
    print(f"[OK] {path} written")
    return 0


def run_check() -> int:
    """Run the Governor self-checks; exit 1 on any failure."""
    from . import engine_contract, quality_gates, safety

    failures: list[str] = []

    contract_violations = engine_contract.validate_all_engines(ENGINE_REGISTRY)
    if contract_violations:
        failures.extend(contract_violations)

    gates = quality_gates.run_all_gates()
    failed = quality_gates.failed_gates(gates)
    if failed:
        failures.append(f"failed gates: {', '.join(failed)}")

    assessment = safety.assess_action("breaking_api_change")
    if assessment.allowed:
        failures.append("safety gate allowed breaking API change without approval")

    print("GOVERNOR SELF-CHECK")
    print("=" * 60)
    if failures:
        print("FAILURES:")
        for failure in failures:
            print(f"  - {failure}")
        print("=" * 60)
        return 1
    print("  [PASS] engine contracts conform")
    print("  [PASS] all quality gates pass")
    print("  [PASS] safety gate blocks dangerous actions")
    print("=" * 60)
    print("RESULT: ALL GOVERNOR CHECKS PASSED")
    return 0


COMMANDS = {
    "audit": run_audit,
    "authority": run_authority,
    "health": run_health,
    "report": run_report,
    "check": run_check,
}


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if not argv or argv[0] in {"-h", "--help", "help"}:
        print(__doc__)
        return 0
    command = argv[0]
    if command not in COMMANDS:
        print(f"Unknown command: {command}")
        print("Available: " + ", ".join(sorted(COMMANDS)))
        return 2
    return COMMANDS[command]()


if __name__ == "__main__":
    sys.exit(main())
