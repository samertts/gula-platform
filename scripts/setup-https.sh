#!/bin/bash
# =============================================================================
# GULA Platform - HTTPS / TLS Setup Script
# Obtains Let's Encrypt certificate and hardens TLS configuration.
#
# What this does:
#   1. Install certbot (if not present)
#   2. Obtain/renew certificate via webroot challenge
#   3. Copy certs to config/ssl/
#   4. Write a hardened nginx TLS config (TLS 1.3 preferred, strong ciphers,
#      OCSP stapling, HSTS, no session tickets)
#   5. Reload nginx in Docker
#   6. Print cron auto-renewal command
#
# Usage: sudo ./scripts/setup-https.sh <domain> [email]
# Example: sudo ./scripts/setup-https.sh lab.example.iq admin@example.iq
# =============================================================================

set -euo pipefail

DOMAIN="${1:?Usage: $0 <domain> [email]}"
EMAIL="${2:-webmaster@${DOMAIN}}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLATFORM_DIR="$(dirname "${SCRIPT_DIR}")"
SSL_DIR="${PLATFORM_DIR}/config/ssl"
NGINX_CONF_DIR="${PLATFORM_DIR}/config/nginx/conf.d"
CERTBOT_WEBROOT="${PLATFORM_DIR}/certbot-webroot"
NGINX_CONTAINER="${NGINX_CONTAINER:-gula-api-gateway}"

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"; }
err() { echo "[ERROR] $*" >&2; exit 1; }

# ─── 1. Install certbot ───────────────────────────────────────────────────────
if ! command -v certbot &>/dev/null; then
    log "Installing certbot..."
    if command -v apt-get &>/dev/null; then
        apt-get update -qq && apt-get install -y certbot
    elif command -v yum &>/dev/null; then
        yum install -y certbot
    else
        err "Cannot install certbot: unsupported package manager. Install manually."
    fi
fi
log "certbot $(certbot --version 2>&1 | head -1)"

# ─── 2. Prepare directories ───────────────────────────────────────────────────
mkdir -p "${SSL_DIR}" "${CERTBOT_WEBROOT}" "${NGINX_CONF_DIR}"

# ─── 3. Obtain / renew certificate ───────────────────────────────────────────
log "Requesting certificate for ${DOMAIN}..."
certbot certonly \
    --webroot \
    --webroot-path "${CERTBOT_WEBROOT}" \
    --domain "${DOMAIN}" \
    --email "${EMAIL}" \
    --agree-tos \
    --non-interactive \
    --keep-until-expiring \
    --quiet

CERT_DIR="/etc/letsencrypt/live/${DOMAIN}"
[[ -f "${CERT_DIR}/fullchain.pem" ]] || err "Certificate not found at ${CERT_DIR}"

# ─── 4. Copy certs to config/ssl/ ────────────────────────────────────────────
log "Copying certificates to ${SSL_DIR}..."
cp "${CERT_DIR}/fullchain.pem" "${SSL_DIR}/fullchain.pem"
cp "${CERT_DIR}/privkey.pem"   "${SSL_DIR}/privkey.pem"
chmod 600 "${SSL_DIR}/privkey.pem"
chmod 644 "${SSL_DIR}/fullchain.pem"

# ─── 5. Generate DH parameters if not present ────────────────────────────────
if [[ ! -f "${SSL_DIR}/dhparam.pem" ]]; then
    log "Generating 2048-bit DH parameters (takes ~30s)..."
    openssl dhparam -out "${SSL_DIR}/dhparam.pem" 2048 2>/dev/null
    log "DH parameters written."
fi

# ─── 6. Write hardened TLS nginx config ──────────────────────────────────────
cat > "${NGINX_CONF_DIR}/ssl.conf" << EOF
# =============================================================================
# GULA Platform - Hardened TLS Configuration
# Generated by scripts/setup-https.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# TLS 1.3 preferred | OCSP stapling | HSTS | No session tickets
#
# This file adds port 443 (HTTPS) and overrides port 80 for this domain
# to redirect to HTTPS.  api.conf remains active as a fallback for
# non-matched hostnames and direct IP access.
# =============================================================================

# ─── HTTPS server ─────────────────────────────────────────────────────────────
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${DOMAIN} www.${DOMAIN};

    # ─── TLS certificates ──────────────────────────────────────────────────
    ssl_certificate     /etc/nginx/ssl/fullchain.pem;
    ssl_certificate_key /etc/nginx/ssl/privkey.pem;
    ssl_dhparam         /etc/nginx/ssl/dhparam.pem;

    # ─── Protocol hardening ────────────────────────────────────────────────
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers on;
    ssl_ciphers 'ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256';

    # ─── Session hardening ────────────────────────────────────────────────
    ssl_session_tickets off;
    ssl_session_cache   shared:SSL:10m;
    ssl_session_timeout 1d;

    # ─── OCSP stapling ────────────────────────────────────────────────────
    ssl_stapling        on;
    ssl_stapling_verify on;
    ssl_trusted_certificate /etc/nginx/ssl/fullchain.pem;
    resolver 8.8.8.8 8.8.4.4 valid=300s;
    resolver_timeout 5s;

    # ─── Security headers ─────────────────────────────────────────────────
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
    add_header X-Content-Type-Options    nosniff always;
    add_header X-Frame-Options           DENY always;
    add_header Referrer-Policy           strict-origin-when-cross-origin always;
    add_header Permissions-Policy        "camera=(), microphone=(), geolocation=()" always;
    add_header Content-Security-Policy   "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' https://${DOMAIN}; font-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none';" always;
    add_header X-Request-ID              \$request_id always;

    server_tokens off;
    proxy_hide_header X-Powered-By;
    proxy_hide_header Server;

    # Block malicious IPs
    if (\$blocked_ip) { return 403 '{"error":"Access denied"}'; }

    limit_conn conn_limit 100;

    # ─── Block sensitive paths ─────────────────────────────────────────────
    location ~ /\\. { deny all; return 404; }
    location ~* (wp-admin|phpmyadmin|\\.env|\\.git|xmlrpc\\.php) { deny all; return 404; }

    # ─── Health checks ─────────────────────────────────────────────────────
    location = /health {
        limit_req zone=health_limit burst=10 nodelay;
        proxy_pass http://gula_backend/health;
        proxy_connect_timeout 5s;
        proxy_read_timeout 10s;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-Proto https;
    }
    location = /health/ready {
        proxy_pass http://gula_backend/health/ready;
        proxy_connect_timeout 3s;
        proxy_read_timeout 5s;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-Proto https;
    }
    location = /health/live {
        return 200 '{"status":"alive","service":"gula-gateway"}';
        add_header Content-Type application/json;
    }

    # ─── Backend API ───────────────────────────────────────────────────────
    location /api/ {
        limit_req zone=api_limit burst=20 nodelay;
        proxy_pass http://gula_backend/;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Request-ID \$request_id;
        proxy_connect_timeout 10s;
        proxy_read_timeout 30s;
        proxy_next_upstream error timeout invalid_header http_502 http_503 http_504;
        proxy_next_upstream_tries 3;
    }

    location /auth/ {
        limit_req zone=auth_limit burst=10 nodelay;
        proxy_pass http://gula_backend/auth/;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_connect_timeout 10s;
        proxy_read_timeout 15s;
    }

    location /mobile/ {
        limit_req zone=api_limit burst=20 nodelay;
        proxy_pass http://gula_backend/mobile/;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Request-ID \$request_id;
        proxy_set_header X-Device-ID \$http_x_device_id;
        proxy_set_header X-App-Version \$http_x_app_version;
        proxy_connect_timeout 10s;
        proxy_read_timeout 30s;
    }

    location /compliance/ {
        limit_req zone=api_limit burst=10 nodelay;
        proxy_pass http://gula_backend/compliance/;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
    }

    location /login {
        limit_req zone=auth_limit burst=5 nodelay;
        proxy_pass http://gula_backend/login;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
    }

    location /upload {
        limit_req zone=upload_limit burst=5 nodelay;
        client_max_body_size 50M;
        proxy_pass http://gula_backend/upload;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-Proto https;
        proxy_read_timeout 120s;
        proxy_send_timeout 120s;
    }

    location /docs  { proxy_pass http://gula_backend/docs;         proxy_set_header Host \$host; }
    location /redoc { proxy_pass http://gula_backend/redoc;        proxy_set_header Host \$host; }
    location /openapi.json { proxy_pass http://gula_backend/openapi.json; proxy_set_header Host \$host; }
    location /r/    { proxy_pass http://gula_frontend/r/;          proxy_set_header Host \$host; }

    # ─── Frontend SPA (catchall) ───────────────────────────────────────────
    location / {
        proxy_pass http://gula_frontend;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_next_upstream error timeout http_502 http_503 http_504;
        proxy_next_upstream_tries 2;
    }

    # ─── Error pages ───────────────────────────────────────────────────────
    error_page 429 /429.json;
    location = /429.json {
        return 429 '{"error":"Rate limit exceeded","retry_after":60}';
        add_header Content-Type application/json;
        add_header Retry-After 60;
    }
    error_page 502 503 504 /50x.json;
    location = /50x.json {
        default_type application/json;
        return 503 '{"error":"Service temporarily unavailable","retry_after":30}';
    }

    client_max_body_size 10M;
}

# ─── HTTP → HTTPS redirect (domain-specific, takes priority over api.conf) ────
server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN} www.${DOMAIN};

    # ACME challenge must pass through over HTTP
    location /.well-known/acme-challenge/ {
        root /var/www/certbot;
    }

    location / {
        return 301 https://\$host\$request_uri;
    }
}
EOF

log "Nginx TLS config written to ${NGINX_CONF_DIR}/ssl.conf"

# ─── 7. Reload nginx in Docker ────────────────────────────────────────────────
if docker ps --format '{{.Names}}' 2>/dev/null | grep -q "^${NGINX_CONTAINER}$"; then
    log "Reloading nginx (container: ${NGINX_CONTAINER})..."
    docker exec "${NGINX_CONTAINER}" nginx -t && docker exec "${NGINX_CONTAINER}" nginx -s reload
    log "Nginx reloaded successfully."
else
    log "WARNING: nginx container '${NGINX_CONTAINER}' not running — reload skipped."
    log "Run manually: docker compose up -d api-gateway"
fi

# ─── 8. Print auto-renewal cron ───────────────────────────────────────────────
log ""
log "============================================================"
log "HTTPS setup complete for ${DOMAIN}"
log "Certificate expires: $(openssl x509 -enddate -noout -in "${SSL_DIR}/fullchain.pem" | cut -d= -f2)"
log ""
log "Add auto-renewal to crontab (crontab -e):"
log "  0 3 * * * certbot renew --quiet --webroot --webroot-path ${CERTBOT_WEBROOT} && \\"
log "            cp /etc/letsencrypt/live/${DOMAIN}/fullchain.pem ${SSL_DIR}/fullchain.pem && \\"
log "            cp /etc/letsencrypt/live/${DOMAIN}/privkey.pem ${SSL_DIR}/privkey.pem && \\"
log "            docker exec ${NGINX_CONTAINER} nginx -s reload"
log "============================================================"
