from __future__ import annotations

import io
import logging
from typing import Any
from dataclasses import dataclass

logger = logging.getLogger("gula.pdf")


@dataclass
class PDFTemplate:
    title: str = "GULA Report"
    subtitle: str = ""
    logo_path: str | None = None
    footer_text: str = "Generated by GULA Platform"
    show_qr: bool = True
    language: str = "ar"


def generate_result_pdf(
    data: dict[str, Any],
    result_url: str = "",
    template: PDFTemplate | None = None,
) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image,
    )
    from shared.qr import generate_qr_image

    tpl = template or PDFTemplate()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, rightMargin=15*mm, leftMargin=15*mm, topMargin=15*mm, bottomMargin=15*mm)
    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph(tpl.title, styles["Title"]))
    if tpl.subtitle:
        elements.append(Paragraph(tpl.subtitle, styles["Subtitle"]))
    elements.append(Spacer(1, 5*mm))

    patient_info = [
        ["Patient Name", data.get("patient_name", "")],
        ["Test", data.get("test_name", "")],
        ["Result", data.get("result_value", "")],
        ["Reference Range", data.get("reference_range", "")],
        ["Date", data.get("date", "")],
    ]
    t = Table(patient_info, colWidths=[100, 300])
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("BACKGROUND", (0, 0), (0, -1), colors.lightgrey),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(t)
    elements.append(Spacer(1, 5*mm))

    if tpl.show_qr and result_url:
        qr_bytes = generate_qr_image(result_url, box_size=4, border=2)
        qr_img = Image(io.BytesIO(qr_bytes), width=50*mm, height=50*mm)
        elements.append(qr_img)

    elements.append(Paragraph(tpl.footer_text, styles["Normal"]))
    doc.build(elements)
    return buf.getvalue()


def generate_pdf(
    content: list[Any],
    title: str = "GULA Report",
) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
    from reportlab.lib.styles import getSampleStyleSheet

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4)
    styles = getSampleStyleSheet()
    elements = [Paragraph(title, styles["Title"]), Spacer(1, 5*mm)]
    elements.extend(content)
    doc.build(elements)
    return buf.getvalue()
