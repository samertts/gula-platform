#!/bin/bash
# GULA Platform — Full Engineering Assessment Generator
# Usage: ./assessment/scripts/generate-assessment.sh
# Output: assessment/reports/full-assessment-<date>.md

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPORT_DIR="$PROJECT_ROOT/assessment/reports"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
REPORT_FILE="$REPORT_DIR/full-assessment-$TIMESTAMP.md"

mkdir -p "$REPORT_DIR"

# Detect Python
PYTHON=""
if [ -f "$PROJECT_ROOT/.venv/bin/python" ]; then
    PYTHON="$PROJECT_ROOT/.venv/bin/python"
elif command -v python3 &>/dev/null; then
    PYTHON="python3"
else
    PYTHON="python"
fi

echo "# GULA Platform — Full Engineering Assessment" > "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "**Date:** $(date '+%Y-%m-%d %H:%M:%S')" >> "$REPORT_FILE"
echo "**Platform Version:** 2.1.0" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Section 1: Code Quality
echo "## 1. Code Quality" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

if [ -d "$PROJECT_ROOT/backend/app" ]; then
    cd "$PROJECT_ROOT"

    echo "### ruff lint" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    $PYTHON -m ruff check backend/app --select=E9,F821 2>&1 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"

    echo "### ruff format" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    $PYTHON -m ruff format --check backend/app 2>&1 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"

    echo "### py_compile" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    find backend/app -name '*.py' -exec $PYTHON -m py_compile {} \; 2>&1 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
fi

# Section 2: Test Results
echo "## 2. Test Results" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

if [ -d "$PROJECT_ROOT/backend/tests" ]; then
    echo "### pytest (core modules)" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    $PYTHON -m pytest "$PROJECT_ROOT/backend/tests/test_security.py" -q --tb=no 2>&1 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
fi

# Section 3: Test Coverage
echo "## 3. Test Coverage" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

if [ -f "$PROJECT_ROOT/.coverage" ] && command -v $PYTHON -m coverage &>/dev/null; then
    echo '```' >> "$REPORT_FILE"
    $PYTHON -m coverage report --sort=-cover 2>&1 | head -30 >> "$REPORT_FILE" || echo "Coverage data not available" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
else
    echo "No coverage data found. Run tests with --cov first." >> "$REPORT_FILE"
fi
echo "" >> "$REPORT_FILE"

# Section 4: Security Scan
echo "## 4. Security Scan" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

if command -v bandit &>/dev/null; then
    echo "### Bandit SAST" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    bandit -r "$PROJECT_ROOT/backend/app" -ll -ii 2>&1 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
fi

# Section 5: Repository Stats
echo "## 5. Repository Statistics" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
echo "Python files in backend/app: $(find "$PROJECT_ROOT/backend/app" -name '*.py' | wc -l)"
if [ -d "$PROJECT_ROOT/.git" ]; then
    echo "Git commits: $(cd "$PROJECT_ROOT" && git rev-list --count HEAD 2>/dev/null || echo 'N/A')"
    echo "Branches: $(cd "$PROJECT_ROOT" && git branch -a 2>/dev/null | wc -l || echo 'N/A')"
fi
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Section 6: Quality Gate Status
echo "## 6. Quality Gate Status" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "| Gate | Status | Details |" >> "$REPORT_FILE"
echo "|------|--------|---------|" >> "$REPORT_FILE"
echo "| A — Backend Foundation | Check | Ruff lint/format, PyCompile, tests |" >> "$REPORT_FILE"
echo "| B — Security Hardening | Check | Bandit, security tests |" >> "$REPORT_FILE"
echo "| C — Testing Hardening | Check | Coverage, test health |" >> "$REPORT_FILE"
echo "| D — Production Readiness | Check | Full certification |" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

echo "---" >> "$REPORT_FILE"
echo "Report auto-generated by assessment/scripts/generate-assessment.sh" >> "$REPORT_FILE"

echo "Report generated: $REPORT_FILE"
