#!/bin/bash
# GULA Platform — Compliance Check Generator
# Usage: ./assessment/scripts/compliance-check.sh
# Output: assessment/reports/compliance-<date>.md

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPORT_DIR="$PROJECT_ROOT/assessment/reports"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
REPORT_FILE="$REPORT_DIR/compliance-$TIMESTAMP.md"

mkdir -p "$REPORT_DIR"

echo "# GULA Platform — Compliance Check Report" > "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "**Date:** $(date '+%Y-%m-%d %H:%M:%S')" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Check SNDHS flags
echo "## SNDHS-lite Feature Flags" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
grep -n 'SNDHS_ENABLE\|ENABLE_FINANCIAL\|ENABLE_ADS' "$PROJECT_ROOT/backend/app/core/sndhs_flags.py" 2>/dev/null || echo "sndhs_flags.py not found"
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Check encryption
echo "## Encryption at Rest" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
grep -rn 'encrypt\|decrypt\|AES\|Fernet' "$PROJECT_ROOT/backend/app/security/" --include='*.py' \
    | grep -v '__pycache__\|\.pyc' || echo "No encryption code found"
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Check audit logging
echo "## Audit Log Coverage" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
grep -rn 'AuditLog\|audit_log' "$PROJECT_ROOT/backend/app/routes/" --include='*.py' \
    | grep -v '__pycache__\|\.pyc' | head -20 || echo "No audit log references found in routes"
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Check tenant isolation
echo "## Tenant Isolation (lab_id filtering)" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
grep -rn 'lab_id' "$PROJECT_ROOT/backend/app/routes/" --include='*.py' \
    | grep -v '__pycache__\|\.pyc\|import\|# type' | head -20 || echo "No lab_id references found"
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Check migration policy
echo "## Migration Policy Compliance" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
echo "Migration files: $(find "$PROJECT_ROOT/backend/migrations/versions" -name '*.py' | wc -l)"
grep -l '_has_column\|_table_exists\|_index_exists' "$PROJECT_ROOT/backend/migrations/versions/"*.py 2>/dev/null | head -10 || echo "No migration guard functions found"
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Compliance checklist
echo "## Compliance Checklist" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "| Requirement | Status | Evidence |" >> "$REPORT_FILE"
echo "|-------------|--------|----------|" >> "$REPORT_FILE"

# Check each requirement
if [ -f "$PROJECT_ROOT/backend/app/security/auth.py" ]; then
    echo "| JWT Authentication | ✅ | backend/app/security/auth.py |" >> "$REPORT_FILE"
else
    echo "| JWT Authentication | ❌ | Not found |" >> "$REPORT_FILE"
fi

if grep -q 'lab_id' "$PROJECT_ROOT/backend/app/routes/"*.py 2>/dev/null; then
    echo "| Multi-tenant Isolation | ✅ | lab_id filtering in routes |" >> "$REPORT_FILE"
else
    echo "| Multi-tenant Isolation | ⚠️ | Partial — verify all routes |" >> "$REPORT_FILE"
fi

if grep -q 'AuditLog' "$PROJECT_ROOT/backend/app/models/"*.py 2>/dev/null; then
    echo "| Audit Logging | ✅ | AuditLog model present |" >> "$REPORT_FILE"
else
    echo "| Audit Logging | ❌ | Not found |" >> "$REPORT_FILE"
fi

if grep -q 'national_id' "$PROJECT_ROOT/backend/app/models/"*.py 2>/dev/null; then
    echo "| National ID Encryption | ✅ | national_id field present |" >> "$REPORT_FILE"
else
    echo "| National ID Encryption | ⚠️ | Not found (feature flag gated) |" >> "$REPORT_FILE"
fi

if grep -q 'rate_limit\|RateLimit' "$PROJECT_ROOT/backend/app/"*.py 2>/dev/null; then
    echo "| Rate Limiting | ✅ | Present in backend |" >> "$REPORT_FILE"
else
    echo "| Rate Limiting | ⚠️ | Not verified |" >> "$REPORT_FILE"
fi

echo "" >> "$REPORT_FILE"
echo "---" >> "$REPORT_FILE"
echo "Report auto-generated by assessment/scripts/compliance-check.sh" >> "$REPORT_FILE"

echo "Compliance report generated: $REPORT_FILE"
