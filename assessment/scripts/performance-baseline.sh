#!/bin/bash
# GULA Platform — Performance Baseline Generator
# Usage: ./assessment/scripts/performance-baseline.sh [endpoint]
# Requires: Running backend instance

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPORT_DIR="$PROJECT_ROOT/assessment/reports"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)

BASE_URL="${1:-http://localhost:8000}"
REPORT_FILE="$REPORT_DIR/performance-baseline-$TIMESTAMP.md"

mkdir -p "$REPORT_DIR"

echo "# GULA Platform — Performance Baseline" > "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "**Date:** $(date '+%Y-%m-%d %H:%M:%S')" >> "$REPORT_FILE"
echo "**Target:** $BASE_URL" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Health check
echo "## Health Endpoints" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

for endpoint in /health /health/ready /health/deep; do
    url="$BASE_URL$endpoint"
    echo "### $endpoint" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    curl -s -o /dev/null -w "HTTP %{http_code}, Time: %{time_total}s\n" "$url" 2>&1 || echo "Failed to reach $url"
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
done

# Simple latency test
echo "## Endpoint Latency" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "| Endpoint | Min (s) | Avg (s) | Max (s) | HTTP |" >> "$REPORT_FILE"
echo "|----------|---------|---------|---------|------|" >> "$REPORT_FILE"

for endpoint in /health /health/ready /health/deep; do
    url="$BASE_URL$endpoint"
    min=999
    max=0
    avg=0
    for i in $(seq 1 5); do
        time=$(curl -s -o /dev/null -w "%{time_total}" "$url" 2>/dev/null || echo "0")
        stat=$(python3 -c "print($time if $time > 0 else 0)" 2>/dev/null || echo "0")
        avg=$(python3 -c "print(($avg + $stat) if $i == 1 else ($avg * ($i-1) + $stat) / $i)" 2>/dev/null || echo "0")
        if [ "$(python3 -c "print($stat < $min)" 2>/dev/null)" = "True" ]; then min=$stat; fi
        if [ "$(python3 -c "print($stat > $max)" 2>/dev/null)" = "True" ]; then max=$stat; fi
    done
    http_code=$(curl -s -o /dev/null -w "%{http_code}" "$url" 2>/dev/null || echo "000")
    echo "| $endpoint | ${min}s | ${avg}s | ${max}s | $http_code |" >> "$REPORT_FILE"
done

echo "" >> "$REPORT_FILE"
echo "---" >> "$REPORT_FILE"
echo "Report auto-generated by assessment/scripts/performance-baseline.sh" >> "$REPORT_FILE"

echo "Performance baseline generated: $REPORT_FILE"
