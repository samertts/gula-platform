#!/bin/bash
# GULA Platform — Security Scan Generator
# Usage: ./assessment/scripts/security-scan.sh
# Output: assessment/reports/security-scan-<date>.md

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPORT_DIR="$PROJECT_ROOT/assessment/reports"
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
REPORT_FILE="$REPORT_DIR/security-scan-$TIMESTAMP.md"

mkdir -p "$REPORT_DIR"

echo "# GULA Platform — Security Scan Report" > "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo "**Date:** $(date '+%Y-%m-%d %H:%M:%S')" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Bandit scan
if command -v bandit &>/dev/null; then
    echo "## Bandit SAST Scan" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    bandit -r "$PROJECT_ROOT/backend/app" -ll -ii 2>&1 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
else
    echo "## Bandit SAST Scan" >> "$REPORT_FILE"
    echo "Bandit not installed. Install with: pip install bandit" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
fi

# Security test results
PYTHON=""
if [ -f "$PROJECT_ROOT/.venv/bin/python" ]; then
    PYTHON="$PROJECT_ROOT/.venv/bin/python"
elif command -v python3 &>/dev/null; then
    PYTHON="python3"
else
    PYTHON="python"
fi

echo "## Security Test Results" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
$PYTHON -m pytest "$PROJECT_ROOT/backend/tests/test_security.py" -q --tb=short 2>&1 >> "$REPORT_FILE" || true
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Secrets check
echo "## Hardcoded Secrets Check" >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"
# Check for common secret patterns not using env vars
grep -rn 'SECRET_KEY\|ENCRYPTION_KEY\|NID_HMAC_KEY\|REFRESH_TOKEN_SECRET\|DEVICE_HMAC_KEY' \
    "$PROJECT_ROOT/backend/app" --include='*.py' \
    | grep -v 'getenv\|environ\|config\|os\.environ' \
    | grep -v '.env\|__pycache__' || echo "No hardcoded secrets found"
echo '```' >> "$REPORT_FILE"
echo "" >> "$REPORT_FILE"

# Gitleaks check
if command -v gitleaks &>/dev/null; then
    echo "## Gitleaks Scan" >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
    gitleaks detect --source "$PROJECT_ROOT" --no-git -v 2>&1 | head -20 >> "$REPORT_FILE" || true
    echo '```' >> "$REPORT_FILE"
    echo "" >> "$REPORT_FILE"
fi

echo "---" >> "$REPORT_FILE"
echo "Report auto-generated by assessment/scripts/security-scan.sh" >> "$REPORT_FILE"

echo "Security report generated: $REPORT_FILE"
