#!/bin/bash
# =============================================================================
# GULA Platform — WAL Archiving & Backup Configuration (pgBackRest)
# =============================================================================
# This script configures pgBackRest for:
#   - Continuous WAL archiving
#   - Daily full backups
#   - Hourly incremental backups
#   - Retention: 30 daily, 12 monthly
#   - Point-in-Time Recovery (PITR) procedures
#
# Prerequisites:
#   - pgBackRest installed (pgbackrest)
#   - S3/MinIO endpoint accessible
#   - PostgreSQL 16 with archive_mode = on
#
# Restore procedure:
#   sudo -u postgres pgbackrest --stanza=gula --delta restore
#   # Or PITR to a specific time:
#   sudo -u postgres pgbackrest --stanza=gula --type=time "--target=2026-06-01 14:30:00+03" --target-action=promote --delta restore
# =============================================================================

set -euo pipefail

# ── Configuration (override via environment) ─────────────────────────────────
BACKUP_DIR="${BACKUP_DIR:-/var/lib/pgbackrest}"
STANZA="${STANZA:-gula}"
DB_VERSION="${DB_VERSION:-16}"
DB_PATH="${DB_PATH:-/var/lib/postgresql/${DB_VERSION}/main}"
PG_BIN_PATH="${PG_BIN_PATH:-/usr/lib/postgresql/${DB_VERSION}/bin}"

# S3/MinIO Configuration
S3_BUCKET="${S3_BUCKET:-gula-db-backups}"
S3_ENDPOINT="${S3_ENDPOINT:-s3.me-central-1.amazonaws.com}"
S3_REGION="${S3_REGION:-me-central-1}"
S3_KEY="${S3_KEY:?S3_KEY must be set}"
S3_KEY_SECRET="${S3_KEY_SECRET:?S3_KEY_SECRET must be set}"
S3_BUCKET_PREFIX="${S3_BUCKET_PREFIX:-pgbackrest}"

# Retention
RETENTION_FULL="${RETENTION_FULL:-30}"    # Keep 30 daily full backups
RETENTION_DIFF="${RETENTION_DIFF:-7}"     # Keep 7 differential backups
RETENTION_ARCHIVE="${RETENTION_ARCHIVE:-60}"  # Keep WAL archives for 60 days
RETENTION_MONTHLY="${RETENTION_MONTHLY:-12}"  # Keep 12 monthly (full)

# Alerting
ALERT_WEBHOOK_URL="${ALERT_WEBHOOK_URL:-}"

LOG_FILE="/var/log/gula/backup-config.log"
mkdir -p "$(dirname "$LOG_FILE")" "$BACKUP_DIR"

# ── Logging ──────────────────────────────────────────────────────────────────
log()  { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*" | tee -a "$LOG_FILE"; }
ok()   { log "✓ $*"; }
warn() { log "⚠ $*"; }
err()  { log "✗ $*"; }

# ── pgBackRest Configuration Generation ──────────────────────────────────────

gen_pgbackrest_config() {
    local config_file="${1:-/etc/pgbackrest/pgbackrest.conf}"
    mkdir -p "$(dirname "$config_file")"

    cat > "$config_file" << PGBACKREST_EOF
# =============================================================================
# pgBackRest Configuration — GULA Platform
# Auto-generated by backup-config.sh
# =============================================================================

[${STANZA}]
pg1-path=${DB_PATH}
pg1-port=5432
pg1-user=postgres

# Backup destination (local staging + S3 archive)
repo1-path=${BACKUP_DIR}/${STANZA}
repo1-retention-full=${RETENTION_FULL}
repo1-retention-diff=${RETENTION_DIFF}
repo1-retention-archive=${RETENTION_ARCHIVE}
repo1-cipher-type=none

# S3 remote repository (MinIO or AWS S3 — must be the primary backup target)
repo2-type=s3
repo2-s3-bucket=${S3_BUCKET}
repo2-s3-endpoint=${S3_ENDPOINT}
repo2-s3-region=${S3_REGION}
repo2-s3-key=${S3_KEY}
repo2-s3-key-secret=${S3_KEY_SECRET}
repo2-s3-bucket-prefix=${S3_BUCKET_PREFIX}
repo2-s3-uri-style=path
repo2-retention-full=${RETENTION_FULL}
repo2-retention-diff=${RETENTION_DIFF}
repo2-retention-archive=${RETENTION_ARCHIVE}
repo2-cipher-type=none

# Compression
compress-type=zst
compress-level=6

# Parallelism (matches vCPU count)
process-max=4
process-max-runtime=14400

# Buffer settings (tune for 4GB RAM)
buffer-size=512K
buffer-hard-max=1024M

# S3 settings
s3-connection-max=4

# Logging
log-level-console=info
log-level-file=detail
log-path=/var/log/pgbackrest

# Stanza operations
[global]
repo1-path=${BACKUP_DIR}/${STANZA}
repo1-retention-full=${RETENTION_FULL}
repo1-retention-diff=${RETENTION_DIFF}
repo1-retention-archive=${RETENTION_ARCHIVE}
repo2-path=${BACKUP_DIR}/${STANZA}
repo2-retention-full=${RETENTION_FULL}
repo2-retention-diff=${RETENTION_DIFF}
repo2-retention-archive=${RETENTION_ARCHIVE}
PGBACKREST_EOF

    ok "pgBackRest config written to ${config_file}"
}

# ── PostgreSQL Archive Configuration ─────────────────────────────────────────

configure_archive() {
    local pg_conf="${1:-/etc/postgresql/${DB_VERSION}/main/postgresql.conf}"

    log "Configuring WAL archiving in ${pg_conf}..."

    # Set archive_mode and archive_command via ALTER SYSTEM (idempotent)
    if command -v psql &>/dev/null && [[ -n "${POSTGRES_PASSWORD:-}" ]]; then
        PGPASSWORD="${POSTGRES_PASSWORD}" psql -U postgres -d postgres -c \
            "ALTER SYSTEM SET archive_mode = 'on';" 2>/dev/null || true
        PGPASSWORD="${POSTGRES_PASSWORD}" psql -U postgres -d postgres -c \
            "ALTER SYSTEM SET archive_command = 'pgbackrest --stanza=${STANZA} archive-push %p';" 2>/dev/null || true
        PGPASSWORD="${POSTGRES_PASSWORD}" psql -U postgres -d postgres -c \
            "ALTER SYSTEM SET archive_timeout = '60s';" 2>/dev/null || true
        ok "PostgreSQL archive settings applied via ALTER SYSTEM"
    else
        # Fallback: direct config file manipulation
        sed -i "s|^#*archive_mode.*|archive_mode = on|" "$pg_conf" 2>/dev/null || \
            echo "archive_mode = on" >> "$pg_conf"
        sed -i "s|^#*archive_command.*|archive_command = 'pgbackrest --stanza=${STANZA} archive-push %p'|" "$pg_conf" 2>/dev/null || \
            echo "archive_command = 'pgbackrest --stanza=${STANZA} archive-push %p'" >> "$pg_conf"
        sed -i "s|^#*archive_timeout.*|archive_timeout = 60|" "$pg_conf" 2>/dev/null || \
            echo "archive_timeout = 60" >> "$pg_conf"
        ok "PostgreSQL archive settings written to ${pg_conf}"
    fi
}

# ── Stanza Creation ──────────────────────────────────────────────────────────

create_stanza() {
    log "Creating pgBackRest stanza '${STANZA}'..."
    if pgbackrest --stanza="${STANZA}" stanza-create 2>&1 | tee -a "$LOG_FILE"; then
        ok "Stanza '${STANZA}' created"
    else
        err "Stanza creation failed — check /var/log/pgbackrest/"
        exit 1
    fi
}

# ── Full backup ──────────────────────────────────────────────────────────────

run_full_backup() {
    log "Starting full backup (type=full)..."
    if pgbackrest --stanza="${STANZA}" --type=full backup 2>&1 | tee -a "$LOG_FILE"; then
        ok "Full backup completed"
        _send_backup_alert "SUCCESS" "Full backup completed successfully"
    else
        err "Full backup FAILED"
        _send_backup_alert "FAILURE" "Full backup FAILED — check /var/log/pgbackrest/"
        return 1
    fi
}

# ── Incremental (differential) backup ────────────────────────────────────────

run_incr_backup() {
    log "Starting incremental backup (type=diff)..."
    if pgbackrest --stanza="${STANZA}" --type=diff backup 2>&1 | tee -a "$LOG_FILE"; then
        ok "Incremental backup completed"
    else
        warn "Incremental backup had issues — check logs"
        return 1
    fi
}

# ── Retention cleanup ────────────────────────────────────────────────────────

expire_backups() {
    log "Running retention policy (full=${RETENTION_FULL}, diff=${RETENTION_DIFF}, archive=${RETENTION_ARCHIVE})..."
    pgbackrest --stanza="${STANZA}" --repo1-retention-full="${RETENTION_FULL}" \
        --repo1-retention-diff="${RETENTION_DIFF}" \
        --repo1-retention-archive="${RETENTION_ARCHIVE}" \
        expire 2>&1 | tee -a "$LOG_FILE" || warn "Retention expiry had issues"
    # Same for S3 repo
    pgbackrest --stanza="${STANZA}" --repo=2 \
        --repo2-retention-full="${RETENTION_FULL}" \
        --repo2-retention-diff="${RETENTION_DIFF}" \
        --repo2-retention-archive="${RETENTION_ARCHIVE}" \
        expire 2>&1 | tee -a "$LOG_FILE" || warn "S3 retention expiry had issues"
    ok "Retention policy applied"
}

# Monthly snapshot (promote a full backup to monthly retention)
create_monthly_snapshot() {
    log "Creating monthly backup snapshot..."
    # Monthly is just a full backup that gets labelled differently in the retention
    if pgbackrest --stanza="${STANZA}" --type=full --set="monthly_$(date +%Y%m)" backup 2>&1 | tee -a "$LOG_FILE"; then
        ok "Monthly backup created"
        # Extend retention for monthly — keep it forever (or until monthly retention expires)
        pgbackrest --stanza="${STANZA}" --repo1-retention-full="${RETENTION_MONTHLY}" \
            --repo1-retention-archive="${RETENTION_ARCHIVE}" \
            expire 2>&1 | tee -a "$LOG_FILE" || true
    else
        warn "Monthly backup had issues"
    fi
}

# ── PITR (Point-in-Time Recovery) ────────────────────────────────────────────

pitr_restore() {
    local target_time="${1:?Usage: $0 pitr \"2026-06-01 14:30:00+03\"}"
    local restore_path="${2:-/var/lib/postgresql/${DB_VERSION}/main}"
    log "Starting PITR restore to timestamp: ${target_time}"
    log "Restore path: ${restore_path}"
    warn "This will OVERWRITE the current data directory!"
    warn "Ensure PostgreSQL is STOPPED before proceeding."

    if [[ "${FORCE_PITR:-false}" != "true" ]]; then
        warn "Set FORCE_PITR=true to actually execute"
        log "Dry-run command:"
        log "  sudo -u postgres pgbackrest --stanza=${STANZA} \\"
        log "    --type=time \"--target=${target_time}\" \\"
        log "    --target-action=promote --delta restore"
        return 0
    fi

    pgbackrest --stanza="${STANZA}" \
        --type=time "--target=${target_time}" \
        --target-action=promote \
        --delta \
        restore 2>&1 | tee -a "$LOG_FILE"

    ok "PITR restore completed. Start PostgreSQL to verify."
}

# ── Verify latest backup ─────────────────────────────────────────────────────

verify_backups() {
    log "Verifying latest backup integrity..."
    pgbackrest --stanza="${STANZA}" check 2>&1 | tee -a "$LOG_FILE"
    ok "Backup verification complete"
}

# ── Alert ────────────────────────────────────────────────────────────────────

_send_backup_alert() {
    local status="$1"
    local message="$2"
    if [[ -n "${ALERT_WEBHOOK_URL:-}" ]]; then
        curl -sf -X POST --max-time 5 \
            -H "Content-Type: application/json" \
            -d "{\"text\":\"[GULA Backup] ${status}: ${message}\",\"service\":\"pgbackrest\",\"event\":\"backup\"}" \
            "$ALERT_WEBHOOK_URL" 2>/dev/null || true
    fi
}

# ── Crontab Setup ────────────────────────────────────────────────────────────

setup_crontab() {
    local script_path
    script_path="$(readlink -f "$0")"
    log "Setting up crontab entries for automated backups..."

    crontab -l 2>/dev/null | grep -v "backup-config.sh" > /tmp/crontab.tmp || true

    cat >> /tmp/crontab.tmp << CRON_EOF

# GULA PostgreSQL Backups (pgBackRest)
# Full backup daily at 02:00
0 2 * * * root ${script_path} full
# Incremental backup hourly
0 * * * * root ${script_path} incr
# Monthly snapshot on the 1st at 03:00
0 3 1 * * root ${script_path} monthly
# Verify latest backup daily at 06:00
0 6 * * * root ${script_path} verify
CRON_EOF

    crontab /tmp/crontab.tmp
    ok "Crontab entries installed"
}

# ── Main ─────────────────────────────────────────────────────────────────────

main() {
    local action="${1:-install}"

    case "$action" in
        install|config)
            gen_pgbackrest_config
            configure_archive
            create_stanza
            setup_crontab
            verify_backups
            ok "pgBackRest fully configured and operational"
            ;;
        full)
            run_full_backup
            expire_backups
            ;;
        incr|incremental)
            run_incr_backup
            ;;
        monthly)
            create_monthly_snapshot
            expire_backups
            ;;
        verify)
            verify_backups
            ;;
        pitr)
            pitr_restore "${2:-}"
            ;;
        expire)
            expire_backups
            ;;
        *)
            cat << USAGE
Usage: $0 <action> [args]

Actions:
  install          Full configuration + stanza create + crontab
  full             Run full backup + expiry
  incr             Run incremental (differential) backup
  monthly          Create monthly full backup snapshot
  verify           Verify backup integrity
  pitr <timestamp> PITR restore to target time
  expire           Apply retention policy

Environment:
  S3_KEY, S3_KEY_SECRET    S3/MinIO credentials (required)
  POSTGRES_PASSWORD        PostgreSQL password
  ALERT_WEBHOOK_URL        Alerting webhook URL
  FORCE_PITR=true          Actually execute PITR (dry-run without)

Examples:
  # Initial setup
  S3_KEY=... S3_KEY_SECRET=... $0 install

  # PITR restore to yesterday 14:30
  FORCE_PITR=true $0 pitr "2026-06-01 14:30:00+03"
USAGE
            exit 1
            ;;
    esac
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main "$@"
fi
