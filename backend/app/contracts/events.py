def get_asyncapi_spec() -> dict:
    channels = {}
    for event_name, event_def in EVENT_REGISTRY.items():
        topic = event_name.replace(  # camelCase → kebab-case
            event_name[0],
            event_name[0].lower(),
            1,
        )
        topic = "".join([f"-{c.lower()}" if c.isupper() else c for c in topic]).lstrip("-")
        topic = topic.replace("_", "-")
        channels[f"gula.{topic}"] = {
            "description": event_def["description"],
            "subscribe": {
                "summary": event_def.get("summary", ""),
                "message": {
                    "name": event_name,
                    "title": event_name,
                    "summary": event_def["description"],
                    "contentType": "application/json",
                    "payload": event_def["payload"],
                    "tags": [{"name": t} for t in event_def.get("tags", [])],
                    "correlationId": {
                        "location": f"$message.payload#/{event_def['correlation_id']}",
                    },
                },
            },
        }

    return {
        "asyncapi": "2.6.0",
        "info": {
            "title": "GULA Platform Events",
            "version": "2.1.0",
            "description": "Event-driven message bus for the GULA healthcare platform",
            "contact": {
                "name": "GULA Platform Support",
                "url": "https://gula-platform.org",
                "email": "support@gula-platform.org",
            },
        },
        "servers": {
            "production": {
                "url": "mqtts://events.gula-platform.org:8883",
                "protocol": "mqtt",
                "description": "Production MQTT broker",
            },
            "development": {
                "url": "mqtt://localhost:1883",
                "protocol": "mqtt",
                "description": "Local development MQTT broker",
            },
        },
        "defaultContentType": "application/json",
        "channels": channels,
    }


def get_event_catalog() -> list[dict]:
    return [
        {
            "name": name,
            "description": defn["description"],
            "version": defn["version"],
            "summary": defn.get("summary", ""),
            "tags": defn.get("tags", []),
            "correlation_id": defn.get("correlation_id"),
            "payload_schema": defn["payload"],
        }
        for name, defn in EVENT_REGISTRY.items()
    ]
