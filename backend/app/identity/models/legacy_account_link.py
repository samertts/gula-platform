from __future__ import annotations

from datetime import datetime
from enum import StrEnum

from sqlalchemy import Column, DateTime, ForeignKey, Integer, String, Text

from app._compat import UTC
from app.identity.base import IdentityBaseEntity


class LegacyAccountLinkSource(StrEnum):
    user = "user"
    lab_user = "lab_user"


# Backward-compatible alias for early Wave 3 drafts.
LegacyAccountSource = LegacyAccountLinkSource


class LegacyAccountLinkStatus(StrEnum):
    pending = "pending"
    validated = "validated"
    migrated = "migrated"
    collision = "collision"
    rolled_back = "rolled_back"
    blocked = "blocked"


class LegacyAccountLink(IdentityBaseEntity):
    """Reversible, non-destructive bridge from legacy accounts to NIAM accounts.

    This model intentionally stores no raw email, phone, national ID, password, or
    token. The source fingerprint is an HMAC generated by the mapping service.
    """

    __tablename__ = "niam_legacy_account_links"

    source_kind = Column(String(20), nullable=False)
    legacy_account_id = Column(Integer, nullable=False)
    canonical_account_id = Column(
        String(26), ForeignKey("niam_accounts.id", ondelete="SET NULL"), nullable=True, index=True
    )
    source_fingerprint = Column(String(128), nullable=False, index=True)
    status = Column(String(20), nullable=False, default=LegacyAccountLinkStatus.pending.value, index=True)
    collision_reason = Column(Text, nullable=True)
    mapping_version = Column(Integer, nullable=False, default=1)
    rollback_token = Column(String(64), nullable=False, unique=True)
    validated_at = Column(DateTime(timezone=True), nullable=True)
    migrated_at = Column(DateTime(timezone=True), nullable=True)
    rolled_back_at = Column(DateTime(timezone=True), nullable=True)

    def transition(self, target: LegacyAccountLinkStatus, *, reason: str | None = None) -> None:
        """Apply only an allowed state transition; caller owns the transaction/audit."""
        current = LegacyAccountLinkStatus(self.status)
        allowed: dict[LegacyAccountLinkStatus, set[LegacyAccountLinkStatus]] = {
            LegacyAccountLinkStatus.pending: {
                LegacyAccountLinkStatus.validated,
                LegacyAccountLinkStatus.collision,
                LegacyAccountLinkStatus.blocked,
            },
            LegacyAccountLinkStatus.validated: {
                LegacyAccountLinkStatus.migrated,
                LegacyAccountLinkStatus.collision,
                LegacyAccountLinkStatus.blocked,
            },
            LegacyAccountLinkStatus.migrated: {LegacyAccountLinkStatus.rolled_back},
            LegacyAccountLinkStatus.collision: {
                LegacyAccountLinkStatus.pending,
                LegacyAccountLinkStatus.blocked,
            },
            LegacyAccountLinkStatus.blocked: {LegacyAccountLinkStatus.pending},
            LegacyAccountLinkStatus.rolled_back: {LegacyAccountLinkStatus.pending},
        }
        if target == current:
            return
        if target not in allowed[current]:
            raise ValueError(f"Invalid legacy account mapping transition: {current} -> {target}")
        if target in {
            LegacyAccountLinkStatus.collision,
            LegacyAccountLinkStatus.blocked,
        } and not reason:
            raise ValueError(f"A reason is required for transition to {target.value}")
        if target == LegacyAccountLinkStatus.rolled_back and not self.rollback_token:
            raise ValueError("A rollback token is required before rollback")

        now = datetime.now(UTC)
        self.status = target.value
        if target in {
            LegacyAccountLinkStatus.collision,
            LegacyAccountLinkStatus.blocked,
        }:
            self.collision_reason = reason
        elif target == LegacyAccountLinkStatus.pending:
            self.collision_reason = None
        self.mapping_version = (self.mapping_version or 1) + 1
        if target == LegacyAccountLinkStatus.validated:
            self.validated_at = now
        elif target == LegacyAccountLinkStatus.migrated:
            self.migrated_at = now
        elif target == LegacyAccountLinkStatus.rolled_back:
            self.rolled_back_at = now
