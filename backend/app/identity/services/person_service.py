from __future__ import annotations

import uuid
from datetime import date, datetime
from typing import Optional

from sqlalchemy.ext.asyncio import AsyncSession

from app._compat import UTC
from app.identity.models.person import Person
from app.identity.repositories.person_repository import PersonRepository


class PersonService:

    def __init__(self, session: AsyncSession) -> None:
        self.repo = PersonRepository(session)

    async def create_person(
        self,
        given_name: str,
        family_name: str,
        middle_name: Optional[str] = None,
        full_name_ar: Optional[str] = None,
        gender: Optional[str] = None,
        birth_date: Optional[date] = None,
        nationality: str = "IRQ",
        email: Optional[str] = None,
        phone: Optional[str] = None,
        address: Optional[str] = None,
        national_id_hash: Optional[str] = None,
        health_id: Optional[str] = None,
        passport_number: Optional[str] = None,
        tags: Optional[dict] = None,
    ) -> Person:
        person = Person(
            id=...,  # auto-generated by DB
            uuid=str(uuid.uuid4()),
            national_id_hash=national_id_hash,
            health_id=health_id,
            passport_number=passport_number,
            given_name=given_name,
            middle_name=middle_name,
            family_name=family_name,
            full_name_ar=full_name_ar,
            gender=gender,
            birth_date=birth_date,
            nationality=nationality,
            email=email,
            phone=phone,
            address=address,
            tags=tags,
            is_active=True,
        )
        return await self.repo.create(person)

    async def get_person(self, person_id: str) -> Optional[Person]:
        return await self.repo.get_by_id(person_id)

    async def get_person_by_uuid(self, uuid_str: str) -> Optional[Person]:
        return await self.repo.get_by_uuid(uuid_str)

    async def find_by_health_id(self, health_id: str) -> Optional[Person]:
        return await self.repo.find_by_health_id(health_id)

    async def find_by_phone(self, phone: str) -> Optional[Person]:
        return await self.repo.find_by_phone(phone)

    async def find_by_email(self, email: str) -> Optional[Person]:
        return await self.repo.find_by_email(email)

    async def deactivate_person(self, person_id: str) -> None:
        await self.repo.soft_delete(person_id)

    async def update_person(self, person_id: str, **kwargs) -> Optional[Person]:
        person = await self.repo.get_by_id(person_id)
        if not person:
            return None
        for key, value in kwargs.items():
            if hasattr(person, key) and value is not None:
                setattr(person, key, value)
        await self.repo.session.flush()
        return person
