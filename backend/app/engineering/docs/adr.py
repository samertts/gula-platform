from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

from backend.app.engineering.generators.base import BaseGenerator, GenerateResult


@dataclass
class ADRSpec:
    title: str
    deciders: list[str] = field(default_factory=lambda: ["GULA Engineering"])
    status: str = "proposed"
    context: str = ""
    decision: str = ""
    consequences: str = ""
    alternatives: list[dict[str, str]] = field(default_factory=list)
    number: int | None = None


class ADRGenerator(BaseGenerator):
    def generate(self, **kwargs: Any) -> GenerateResult:
        spec = kwargs.get("spec", kwargs.get("adr"))
        if isinstance(spec, dict):
            spec = ADRSpec(**spec)
        if spec is None:
            spec = ADRSpec(title=kwargs.get("title", "Undecided"))

        now = datetime.utcnow()
        num = spec.number or now.strftime("%Y%m%d%H%M%S")
        slug = spec.title.lower().replace(" ", "-").replace("_", "-")
        filename = f"{num:04d}-{slug}" if isinstance(num, int) else f"{num}-{slug}"

        alternatives_section = ""
        if spec.alternatives:
            alt_lines = []
            for i, alt in enumerate(spec.alternatives, 1):
                name = alt.get("name", f"Alternative {i}")
                desc = alt.get("description", "")
                pros = alt.get("pros", "")
                cons = alt.get("cons", "")
                alt_lines.append(f"### {name}\n\n{desc}\n\n- Pros: {pros}\n- Cons: {cons}")
            alternatives_section = (
                "## Considered Alternatives\n\n" + "\n\n".join(alt_lines) + "\n\n"
            )

        content = f"""# ADR-{num}: {spec.title}

- **Status:** {spec.status}
- **Deciders:** {", ".join(spec.deciders)}
- **Date:** {now.strftime("%Y-%m-%d")}

## Context and Problem Statement

{spec.context or "_No context provided._"}

## Decision

{spec.decision or "_No decision recorded._"}

{alternatives_section}## Consequences

{spec.consequences or "_No consequences documented._"}

## Compliance

- [ ] Implementation follows this decision
- [ ] Tests cover the decision outcome
- [ ] Documentation updated

## Notes

- ADR generated by GULA Engineering Platform
"""

        self._write(f"adrs/{filename}.md", content)
        return self._result


class ArchitectureGenerator(BaseGenerator):
    def generate(self, **kwargs: Any) -> GenerateResult:
        system_name = kwargs.get("name", "System")
        description = kwargs.get("description", "")
        layers = kwargs.get("layers", ["presentation", "application", "domain", "infrastructure"])
        components = kwargs.get("components", [])
        relations = kwargs.get("relations", [])

        layers_section = "\n".join(f"- **{l.capitalize()} Layer**" for l in layers)

        comps_section = ""
        if components:
            comps_section = (
                "## Components\n\n"
                + "\n".join(
                    f"- **{c.get('name', 'Component')}** ({c.get('layer', 'application')}): {c.get('description', '')}"
                    for c in components
                )
                + "\n\n"
            )

        rels_section = ""
        if relations:
            rels_section = (
                "## Data Flow\n\n```mermaid\nflowchart TD\n"
                + "\n".join(
                    f"    {r['from']}[{r['from']}] -->|{r.get('label', '')}| {r['to']}[{r['to']}]"
                    for r in relations
                )
                + "\n```\n\n"
            )

        content = f"""# {system_name} Architecture

{description}

## Layers

{layers_section}

{comps_section}{rels_section}## Architecture Decisions

- **Clean Architecture** with dependency inversion
- **Domain-Driven Design** for business logic
- **CQRS** for command/query separation
- **Event-Driven** for cross-module communication

## Constraints

- All external dependencies must be abstracted behind interfaces
- Domain layer has zero external dependencies
- Presentation layer only depends on application layer
"""

        self._write(f"architecture/{system_name.lower().replace(' ', '_')}.md", content)
        return self._result
