from __future__ import annotations

from datetime import datetime

from sqlalchemy import JSON, Column, DateTime, Float, Index, Integer, String, Text
from sqlalchemy import Enum as SAEnum

from app._compat import UTC
from app.national.base import AuditEntity, _ulid
from app.national.rules_engine.domain.enums import (
    RuleCategory,
    RuleOutcome,
    RuleSeverity,
    RuleStatus,
    RuleTrigger,
)


class RuleModel(AuditEntity):
    __tablename__ = "national_rules"

    id = Column(String(26), primary_key=True, default=_ulid)
    name = Column(String(255), nullable=False, index=True)
    description = Column(Text, nullable=True)
    category = Column(SAEnum(RuleCategory), nullable=False, index=True)
    severity = Column(SAEnum(RuleSeverity), nullable=False, default=RuleSeverity.INFO)
    status = Column(SAEnum(RuleStatus), nullable=False, default=RuleStatus.DRAFT, index=True)
    conditions = Column(JSON, nullable=False, default=list)
    actions = Column(JSON, nullable=False, default=list)
    priority = Column(Integer, nullable=False, default=0)
    version = Column(Integer, nullable=False, default=1)
    tags = Column(JSON, nullable=True, default=list)
    effective_from = Column(DateTime(timezone=True), nullable=True)
    effective_to = Column(DateTime(timezone=True), nullable=True)
    metadata_ = Column("metadata", JSON, nullable=True, default=dict)

    created_by = Column(String(100), nullable=True)
    updated_by = Column(String(100), nullable=True)

    __table_args__ = (
        Index("ix_national_rules_category_status", "category", "status"),
        # ix_national_rules_name is auto-generated by index=True on name column
        {"extend_existing": True},
    )

    def to_domain(self):
        from app.national.rules_engine.domain.entities import (
            RuleAction,
            RuleCondition,
            RuleDefinition,
        )

        conditions = []
        for c in self.conditions or []:
            if isinstance(c, dict):
                from app.national.rules_engine.domain.enums import Operator

                conditions.append(
                    RuleCondition(
                        field=c.get("field", ""),
                        operator=Operator(c.get("operator", "eq"))
                        if isinstance(c.get("operator"), str)
                        else c.get("operator"),
                        value=c.get("value"),
                        value_type=c.get("value_type", "string"),
                    ),
                )

        actions = []
        for a in self.actions or []:
            if isinstance(a, dict):
                actions.append(
                    RuleAction(
                        action_type=a.get("action_type", ""),
                        params=a.get("params", {}),
                    ),
                )

        return RuleDefinition(
            id=self.id,
            name=self.name,
            description=self.description or "",
            category=self.category,
            severity=self.severity,
            status=self.status,
            conditions=conditions,
            actions=actions,
            priority=self.priority,
            version=self.version,
            tags=self.tags or [],
            effective_from=self.effective_from,
            effective_to=self.effective_to,
            metadata=self.metadata_ or {},
        )


class RuleEvaluationLog(AuditEntity):
    __tablename__ = "national_rule_evaluation_logs"

    id = Column(String(26), primary_key=True, default=_ulid)
    rule_id = Column(String(26), nullable=False, index=True)
    rule_name = Column(String(255), nullable=True)
    category = Column(SAEnum(RuleCategory), nullable=True)
    outcome = Column(SAEnum(RuleOutcome), nullable=False)
    severity = Column(SAEnum(RuleSeverity), nullable=True)
    trigger = Column(SAEnum(RuleTrigger), nullable=True)
    resource_type = Column(String(100), nullable=True)
    resource_id = Column(String(100), nullable=True)
    context = Column(JSON, nullable=True)
    result = Column(JSON, nullable=True)
    execution_time_ms = Column(Float, nullable=True)
    triggered_at = Column(
        DateTime(timezone=True), nullable=False, default=lambda: datetime.now(UTC),
    )

    __table_args__ = (
        Index("ix_national_rule_eval_logs_rule_id", "rule_id"),
        Index("ix_national_rule_eval_logs_outcome", "outcome"),
        Index("ix_national_rule_eval_logs_triggered_at", "triggered_at"),
        {"extend_existing": True},
    )
