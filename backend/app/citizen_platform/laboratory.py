from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any

from shared.pdf.generator import PDFTemplate, generate_result_pdf

logger = logging.getLogger("gula.citizen.laboratory")


@dataclass
class CitizenLabResult:
    result_id: str = ""
    order_id: str = ""
    lab_name: str = ""
    lab_id: str = ""
    test_name: str = ""
    test_name_ar: str = ""
    value: str = ""
    value_text: str = ""
    unit: str = ""
    reference_range: str = ""
    flag: str = ""
    status: str = ""
    collected_at: str = ""
    validated_at: str = ""
    performed_by: str = ""
    notes: str = ""


class CitizenLabService:
    def __init__(self) -> None:
        self._results: dict[str, list[CitizenLabResult]] = {}

    def get_results(
        self,
        citizen_id: str,
        lab_id: str | None = None,
        date_from: str | None = None,
        date_to: str | None = None,
        status: str | None = None,
        skip: int = 0,
        limit: int = 50,
    ) -> list[CitizenLabResult]:
        results = self._results.get(citizen_id, [])
        if lab_id:
            results = [r for r in results if r.lab_id == lab_id]
        if date_from:
            results = [r for r in results if r.collected_at >= date_from]
        if date_to:
            results = [r for r in results if r.collected_at <= date_to]
        if status:
            results = [r for r in results if r.status == status]
        results.sort(key=lambda r: r.collected_at, reverse=True)
        return results[skip : skip + limit]

    def get_result_by_id(self, citizen_id: str, result_id: str) -> CitizenLabResult | None:
        results = self._results.get(citizen_id, [])
        for r in results:
            if r.result_id == result_id:
                return r
        return None

    def add_result(self, citizen_id: str, result: CitizenLabResult) -> None:
        if citizen_id not in self._results:
            self._results[citizen_id] = []
        self._results[citizen_id].append(result)

    def get_lab_list(self, citizen_id: str) -> list[dict[str, Any]]:
        results = self._results.get(citizen_id, [])
        seen: dict[str, dict[str, Any]] = {}
        for r in results:
            if r.lab_id not in seen:
                seen[r.lab_id] = {"lab_id": r.lab_id, "lab_name": r.lab_name, "result_count": 0}
            seen[r.lab_id]["result_count"] += 1
        return list(seen.values())


class ResultViewer:
    def __init__(self, lab_service: CitizenLabService) -> None:
        self._lab_service = lab_service

    def view_result(self, citizen_id: str, result_id: str) -> CitizenLabResult | None:
        return self._lab_service.get_result_by_id(citizen_id, result_id)

    def get_abnormal_results(self, citizen_id: str) -> list[CitizenLabResult]:
        results = self._lab_service.get_results(citizen_id)
        return [r for r in results if r.flag in ("H", "L", "critical")]

    def get_critical_results(self, citizen_id: str) -> list[CitizenLabResult]:
        results = self._lab_service.get_results(citizen_id)
        return [r for r in results if r.flag == "critical"]


class PDFReportGenerator:
    def generate_result_report(
        self,
        result: CitizenLabResult,
        patient_name: str = "",
        language: str = "ar",
    ) -> bytes:
        data = {
            "patient_name": patient_name,
            "test_name": result.test_name or result.test_name_ar,
            "result_value": result.value or result.value_text or "",
            "reference_range": result.reference_range,
            "date": result.collected_at,
        }
        template = PDFTemplate(
            title="GULA Laboratory Report",
            subtitle=result.lab_name,
            footer_text="Generated by GULA Citizen Platform",
            language=language,
        )
        return generate_result_pdf(data=data, result_url="", template=template)

    def generate_batch_report(
        self,
        results: list[CitizenLabResult],
        patient_name: str = "",
        lab_name: str = "",
        language: str = "ar",
    ) -> bytes:
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import Paragraph, Spacer, Table, TableStyle

        from shared.pdf.generator import generate_pdf

        styles = getSampleStyleSheet()
        elements: list[Any] = [
            Paragraph(f"Laboratory Report - {lab_name}", styles["Title"]),
            Paragraph(f"Patient: {patient_name}", styles["Normal"]),
            Spacer(1, 5 * mm),
        ]
        table_data = [["Test", "Value", "Flag", "Date"]]
        for r in results:
            table_data.append([
                r.test_name or r.test_name_ar,
                r.value or r.value_text or "",
                r.flag or "",
                r.collected_at,
            ])
        t = Table(table_data, colWidths=[120, 120, 60, 100])
        t.setStyle(TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        elements.append(t)
        return generate_pdf(elements, title="Batch Laboratory Report")
