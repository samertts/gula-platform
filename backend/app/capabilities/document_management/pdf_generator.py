from __future__ import annotations

import asyncio
from typing import Any

from app.national.document_platform.application.interfaces import PDFGenerator


class SharedPdfGenerator(PDFGenerator):
    async def generate(
        self,
        content: dict[str, Any],
        template: str = "",
    ) -> bytes:
        return await asyncio.to_thread(self._generate_sync, content, template)

    def _generate_sync(self, content: dict[str, Any], template: str) -> bytes:
        from shared.pdf import PDFTemplate, generate_result_pdf

        tpl = PDFTemplate(
            title=template or "GULA Document",
            subtitle="",
            footer_text="Generated by GULA Platform",
        )
        return generate_result_pdf(data=content, result_url="", template=tpl)
