"""Add the canonical public drug identity to the National Drug Catalog.

NR-003 / ADR-006.  ``pharmacy_drug_catalog.id`` stays an ``Integer`` primary key
and is internal only.  This revision adds ``drug_id``: a server-generated,
immutable, unique UUID4 that becomes the public/canonical GULA drug identity.

It is a GULA *platform* identity — explicitly NOT a Ministry of Health national
registration number.  A future MoH identifier is to be added as an additional
external identifier, not as a replacement for this column or for the primary key.

Design notes:

* Existing ``Integer`` primary key values are preserved.  Nothing is rewritten.
* ``drug_code`` is untouched: it remains a mutable business/catalog code and is
  never used as a foreign key.
* Values are generated by the database (``gen_random_uuid()``, built in from
  PostgreSQL 13).  They are never derived from the primary key, ``drug_code``,
  a GTIN, a timestamp or any client input.
* Backfill happens exactly once.  Every step is guarded, so a re-run is a no-op
  and will not regenerate an identity that already exists.
* Fail-closed: before the ``NOT NULL`` and ``UNIQUE`` constraints are applied,
  the migration re-checks for NULLs and duplicates and aborts with a structured
  diagnostic rather than transforming or discarding data.
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op
from sqlalchemy import inspect, text
from sqlalchemy.dialects import postgresql

revision: str = "20260909_0001"
down_revision: str | None = "20260908_0001"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

_TABLE = "pharmacy_drug_catalog"
_COLUMN = "drug_id"
_INDEX = "ix_pharmacy_drug_catalog_drug_id"
_UNIQUE = "uq_pharmacy_drug_catalog_drug_id"


def _pg() -> bool:
    return op.get_bind().dialect.name == "postgresql"


def _table_exists(table: str) -> bool:
    return inspect(op.get_bind()).has_table(table)


def _has_column(table: str, column: str) -> bool:
    return any(c["name"] == column for c in inspect(op.get_bind()).get_columns(table))


def _index_exists(table: str, name: str) -> bool:
    return any(i["name"] == name for i in inspect(op.get_bind()).get_indexes(table))


def _constraint_exists(table: str, name: str) -> bool:
    insp = inspect(op.get_bind())
    return any(c["name"] == name for c in insp.get_unique_constraints(table))


def upgrade() -> None:
    if not _table_exists(_TABLE):
        # The pharmacy platform is not installed in this database; nothing to do.
        return

    bind = op.get_bind()

    if not _has_column(_TABLE, _COLUMN):
        op.add_column(
            _TABLE,
            sa.Column(
                _COLUMN,
                postgresql.UUID(as_uuid=True) if _pg() else sa.String(36),
                nullable=True,
            ),
        )

    # Backfill only rows that do not already carry an identity, so a re-run can
    # never regenerate one that has already been published.
    if _pg():
        bind.execute(
            text(f"UPDATE {_TABLE} SET {_COLUMN} = gen_random_uuid() WHERE {_COLUMN} IS NULL")
        )
    else:
        rows = bind.execute(text(f"SELECT id FROM {_TABLE} WHERE {_COLUMN} IS NULL")).fetchall()
        for row in rows:
            bind.execute(
                text(f"UPDATE {_TABLE} SET {_COLUMN} = :value WHERE id = :id"),
                {"value": str(uuid.uuid4()), "id": row[0]},
            )

    # Fail closed.  If either check trips, the transaction rolls back and no
    # constraint is applied; nothing is transformed and nothing is deleted.
    remaining_nulls = bind.execute(
        text(f"SELECT count(*) FROM {_TABLE} WHERE {_COLUMN} IS NULL")
    ).scalar_one()
    if remaining_nulls:
        raise RuntimeError(
            f"NR-003 preflight failed: {remaining_nulls} row(s) in {_TABLE} still have a NULL "
            f"{_COLUMN} after backfill. Aborting before applying NOT NULL; no data was changed."
        )

    duplicates = bind.execute(
        text(
            f"SELECT count(*) FROM (SELECT {_COLUMN} FROM {_TABLE} "
            f"GROUP BY {_COLUMN} HAVING count(*) > 1) AS d"
        )
    ).scalar_one()
    if duplicates:
        raise RuntimeError(
            f"NR-003 preflight failed: {duplicates} duplicate {_COLUMN} value(s) in {_TABLE}. "
            f"Aborting before applying the unique constraint; no data was changed."
        )

    op.alter_column(
        _TABLE,
        _COLUMN,
        existing_type=postgresql.UUID(as_uuid=True) if _pg() else sa.String(36),
        nullable=False,
    )

    if not _constraint_exists(_TABLE, _UNIQUE):
        op.create_unique_constraint(_UNIQUE, _TABLE, [_COLUMN])
    if not _index_exists(_TABLE, _INDEX):
        op.create_index(_INDEX, _TABLE, [_COLUMN])


def downgrade() -> None:
    if not _table_exists(_TABLE):
        return
    if _index_exists(_TABLE, _INDEX):
        op.drop_index(_INDEX, table_name=_TABLE)
    if _constraint_exists(_TABLE, _UNIQUE):
        op.drop_constraint(_UNIQUE, _TABLE, type_="unique")
    if _has_column(_TABLE, _COLUMN):
        op.drop_column(_TABLE, _COLUMN)
