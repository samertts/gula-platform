def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="gula",
        description="GULA Developer CLI — scaffolding, validation, and platform tooling",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")

    subparsers = parser.add_subparsers(dest="command")

    # gula generate
    gen_parser = subparsers.add_parser("generate", help="Generate code scaffolding")
    gen_sub = gen_parser.add_subparsers(dest="kind")

    for k in ("route", "model", "service", "migration", "fhir-profile", "plugin"):
        p = gen_sub.add_parser(k, help=f"Generate a new {k}")
        p.add_argument("name", help=f"Name of the {k}")
        p.add_argument("fields", nargs="*", help="Field definitions (for model: name:type ...)")
        p.add_argument("--output-dir", default=".", help="Output directory")

    # gula validate
    val_parser = subparsers.add_parser("validate", help="Run validation checks")
    val_parser.add_argument(
        "target",
        choices=["architecture", "fhir", "security", "all"],
        help="Validation target",
    )

    # gula doc
    doc_parser = subparsers.add_parser("doc", help="Documentation tools")
    doc_sub = doc_parser.add_subparsers(dest="action")
    doc_gen = doc_sub.add_parser("generate", help="Generate documentation index")
    doc_serve = doc_sub.add_parser("serve", help="Serve documentation via HTTP")
    doc_serve.add_argument("--port", type=int, default=8080, help="HTTP server port")

    # gula knowledge
    know_parser = subparsers.add_parser("knowledge", help="Knowledge graph tools")
    know_sub = know_parser.add_subparsers(dest="action")
    know_sub.add_parser("scan", help="Scan codebase for knowledge graph nodes")

    # gula roadmap
    rm_parser = subparsers.add_parser("roadmap", help="Roadmap management")
    rm_sub = rm_parser.add_subparsers(dest="action")
    rm_sub.add_parser("status", help="Show roadmap status")
    rm_sub.add_parser("list", help="List roadmap phases")

    # gula simulation
    sim_parser = subparsers.add_parser("simulation", help="Digital twin simulation")
    sim_sub = sim_parser.add_subparsers(dest="action")
    sim_run = sim_sub.add_parser("run", help="Run a simulation")
    sim_run.add_argument("twin_id", help="Digital twin identifier")

    # gula contract
    ctr_parser = subparsers.add_parser("contract", help="Contract management")
    ctr_sub = ctr_parser.add_subparsers(dest="action")
    ctr_sub.add_parser("export", help="Export platform contracts")

    # gula platform
    plat_parser = subparsers.add_parser("platform", help="Platform management")
    plat_sub = plat_parser.add_subparsers(dest="action")
    plat_sub.add_parser("status", help="Show platform status")

    return parser


def main(argv: list[str] | None = None) -> None:
    parser = build_parser()
    args = parser.parse_args(argv)

    if not args.command:
        parser.print_help()
        return

    cmd_map = {
        "generate": cmd_generate,
        "validate": _run_validate,
        "doc": cmd_doc,
        "knowledge": cmd_knowledge,
        "roadmap": cmd_roadmap,
        "simulation": cmd_simulation,
        "contract": cmd_contract,
        "platform": cmd_platform,
    }

    handler = cmd_map.get(args.command)
    if handler:
        handler(args)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
