def cmd_generate(args: argparse.Namespace) -> None:
    output_dir = getattr(args, "output_dir", ".")
    kind = args.kind

    generators = {
        "route": RouteGenerator(),
        "model": ModelGenerator(),
        "service": ServiceGenerator(),
        "fhir-profile": FHIRProfileGenerator(),
        "plugin": PluginGenerator(),
    }

    if kind == "migration":
        _generate_migration(args.name)
        return

    gen = generators.get(kind)
    if not gen:
        print(f"Unknown generator: {kind}")
        sys.exit(1)

    fields = getattr(args, "fields", [])

    if kind == "model":
        path = gen.generate(args.name, fields, output_dir)
    else:
        path = gen.generate(args.name, output_dir)

    print(f"Created {path}")


def _generate_migration(name: str) -> None:
    ts = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
    safe_name = name.lower().replace(" ", "_")
    filename = f"{ts}_{safe_name}.py"
    migrations_dir = os.path.join(os.path.dirname(__file__), "..", "backend", "migrations", "versions")
    os.makedirs(migrations_dir, exist_ok=True)
    path = os.path.join(migrations_dir, filename)
    content = f'''"""{safe_name}

Migration generated by GULA CLI.
"""
from alembic import op
import sqlalchemy as sa
from alembic_utils import guard

revision = "{ts}"
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    pass


def downgrade() -> None:
    pass
'''
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"Created migration {path}")


def _run_validate(args: argparse.Namespace) -> None:
    target = args.target
    validators = {
        "architecture": ("Architecture", ArchitectureValidator()),
        "fhir": ("FHIR", FHIRValidator()),
        "security": ("Security", SecurityValidator()),
    }

    def _run_one(label: str, validator) -> dict:
        print(f"\n  [{label} Validator]")
        result = validator.validate_all()
        status = result.get("status", "unknown")
        status_icon = "\u2713" if status == "passed" else ("!" if status == "warning" else "\u2717")
        status_color = "green" if status == "passed" else ("yellow" if status == "warning" else "red")
        print(f"  Status: {status_icon} {status.upper()}")

        for p in result.get("passed", []):
            print(f"    \u2713 {p}")
        for w in result.get("warnings", []):
            print(f"    ! {w}")
        for e in result.get("errors", []):
            print(f"    \u2717 {e}")
        return result

    results = {}
    if target == "all":
        for key, (label, validator) in validators.items():
            results[key] = _run_one(label, validator)
    elif target in validators:
        label, validator = validators[target]
        results[target] = _run_one(label, validator)
    else:
        print(f"Unknown validation target: {target}")
        sys.exit(1)

    _print_validate_summary(results)


def _print_validate_summary(results: dict) -> None:
    overall = "passed"
    for key, result in results.items():
        s = result.get("status", "error")
        if s == "error":
            overall = "error"
        elif s == "warning" and overall != "error":
            overall = "warning"
    print(f"\n  Overall: {overall.upper()}")
    sys.exit(1 if overall == "error" else 0)


def cmd_doc(args: argparse.Namespace) -> None:
    action = args.action
    docs_dir = os.path.join(os.path.dirname(__file__), "..", "docs")

    if action == "generate":
        _generate_docs(docs_dir)
    elif action == "serve":
        _serve_docs(docs_dir)


def _generate_docs(docs_dir: str) -> None:
    readme_path = os.path.join(os.path.dirname(__file__), "..", "README.md")
    if os.path.isfile(readme_path):
        print(f"Documentation root: {readme_path}")

    doc_files = []
    for dirpath, _dirnames, filenames in os.walk(docs_dir):
        for fn in filenames:
            if fn.endswith((".md", ".rst", ".json")):
                doc_files.append(os.path.relpath(os.path.join(dirpath, fn), docs_dir))

    print(f"Found {len(doc_files)} documentation files")
    for f in sorted(doc_files):
        print(f"  {f}")
    print("Documentation index generated.")


def _serve_docs(docs_dir: str) -> None:
    index_path = os.path.join(docs_dir, "index.html")
    if not os.path.isfile(index_path):
        with open(index_path, "w", encoding="utf-8") as fh:
            fh.write("""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>GULA Documentation</title>
<style>body{font-family:sans-serif;margin:2em;max-width:800px;line-height:1.6}
h1{border-bottom:2px solid #0366d6;padding-bottom:.3em}
a{color:#0366d6;text-decoration:none}
a:hover{text-decoration:underline}
</style></head><body>
<h1>GULA Platform Documentation</h1>
<p>Serving documentation from <code>docs/</code></p>
<ul>
""")
            for item in sorted(os.listdir(docs_dir)):
                if os.path.isdir(os.path.join(docs_dir, item)):
                    fh.write(f'<li><a href="{item}/">{item}/</a></li>\n')
                elif item.endswith(".md"):
                    name = item.replace(".md", "").replace("_", " ").title()
                    fh.write(f'<li><a href="{item}">{name}</a></li>\n')
            fh.write("</ul></body></html>")

    port = getattr(getattr(args, "port", None), "port", 8080)
    print(f"Starting documentation server at http://localhost:{port}")
    print("Press Ctrl+C to stop.")
    try:
        subprocess.run(
            [sys.executable, "-m", "http.server", str(port), "--directory", docs_dir],
            check=True,
        )
    except KeyboardInterrupt:
        print("\nDocumentation server stopped.")
    except Exception as exc:
        print(f"Failed to start server: {exc}")
        sys.exit(1)


