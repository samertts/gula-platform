def _scan_knowledge_graph() -> None:
    backend_app = os.path.join(os.path.dirname(__file__), "..", "backend", "app")
    routes_dir = os.path.join(backend_app, "routes")
    models_dir = os.path.join(backend_app, "models")
    services_dir = os.path.join(backend_app, "services")

    print("Scanning codebase for knowledge graph nodes...")
    nodes = []

    if os.path.isdir(routes_dir):
        for fn in os.listdir(routes_dir):
            if fn.endswith(".py") and fn != "__init__.py":
                nodes.append(("route", fn[:-3]))

    if os.path.isdir(models_dir):
        for fn in os.listdir(models_dir):
            if fn.endswith(".py") and fn != "__init__.py":
                nodes.append(("model", fn[:-3]))

    if os.path.isdir(services_dir):
        for fn in os.listdir(services_dir):
            if fn.endswith(".py") and fn != "__init__.py":
                nodes.append(("service", fn[:-3]))

    print(f"Discovered {len(nodes)} nodes:")
    for ntype, nname in sorted(nodes):
        print(f"  [{ntype}] {nname}")


